import { execFile } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { chmod, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { promisify } from 'node:util'

const execute = promisify(execFile)
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const easyEditorRoot = process.env.EASY_EDITOR_WORKSPACE_DIR
  ? resolve(process.env.EASY_EDITOR_WORKSPACE_DIR)
  : resolve(projectRoot, '../EasyEditor')
const executorRoot = resolve(easyEditorRoot, 'spikes/document-executor')
const artifactModulePath = resolve(executorRoot, 'src/workspace-artifacts.mjs')
const manifestProbeModulePath = resolve(executorRoot, 'src/material-manifest-probe.mjs')
const target = resolve(projectRoot, '.env.agent.local')

function isValidEncryptionKey(value) {
  const decoded = Buffer.from(value, 'base64')
  return decoded.length === 32 && decoded.toString('base64') === value
}

async function resolveEncryptionKey() {
  let existingContent = ''
  try {
    existingContent = await readFile(target, 'utf8')
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      throw error
    }
  }

  const existingKey = existingContent.match(/^AGENT_MODEL_PROFILE_ENCRYPTION_KEY=(.+)$/m)?.[1]?.trim()
  return existingKey && isValidEncryptionKey(existingKey) ? existingKey : randomBytes(32).toString('base64')
}

process.stdout.write('Building the isolated EasyEditor Document Executor...\n')
await execute('pnpm', ['build'], { cwd: executorRoot, maxBuffer: 16 * 1024 * 1024 })

const { MATERIAL_MANIFEST_BINDING_VERSION, computeWorkspaceArtifactCompatibility, hashMaterialManifestBinding } =
  await import(pathToFileURL(artifactModulePath).href)
const { probeMaterialManifestBinding } = await import(pathToFileURL(manifestProbeModulePath).href)
const materialManifestBinding = await probeMaterialManifestBinding()
const materialManifestVersion = MATERIAL_MANIFEST_BINDING_VERSION
const materialManifestSha256 = hashMaterialManifestBinding(materialManifestBinding)
const compatibility = await computeWorkspaceArtifactCompatibility({
  materialManifestVersion,
  materialManifestSha256,
})
const grantSecret = randomBytes(32).toString('hex')
const modelProfileEncryptionKey = await resolveEncryptionKey()
const cliPath = resolve(executorRoot, 'src/cli.mjs')
const content = [
  '# Generated by pnpm setup:agent-executor. Local development only.',
  `AGENT_EXECUTOR_GRANT_SECRET=${grantSecret}`,
  `AGENT_MODEL_PROFILE_ENCRYPTION_KEY=${modelProfileEncryptionKey}`,
  `AGENT_EXECUTOR_COMPATIBILITY_JSON=${JSON.stringify(compatibility)}`,
  `AGENT_EXECUTOR_CLI_PATH=${cliPath}`,
  'AGENT_EXECUTOR_DASHBOARD_URL=http://127.0.0.1:4173/index.html',
  'AGENT_EXECUTOR_API_ORIGIN=http://127.0.0.1:5173',
  'AGENT_EXECUTOR_TIMEOUT_MS=120000',
  '',
].join('\n')

await writeFile(target, content, { encoding: 'utf8', mode: 0o600 })
await chmod(target, 0o600)
process.stdout.write(`Document Executor is ready. Local configuration written to ${target}.\n`)
